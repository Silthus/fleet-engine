import { crew, logos, packCast, scenes, teamRole, type Art, type Role, type Tone } from "./cast.ts";
import { packFlows } from "./flows.ts";
import { brandIcons, packIcon, uiIcons } from "./icons.ts";
import { logoMark } from "./logo.ts";
import { firstStart, installPrompt, promptData, startPacksOn, startPrompt, toggleSelected, wheres, type PageData, type PagePack, type Where } from "./model.ts";
import { esc, fmt, promptHtml, t3Link } from "./prompt.ts";

export type ArtSizes = Record<string, { width: number; height: number }>;

export type Route = { path: string; html: string };

type Frame = { root: string; title: string; description: string; current?: "packs"; body: string; data?: unknown };

const boxes: Record<Where, { name: string; sticker: string; fact: string; art: Art; tone: Tone }> = {
  mac: { name: "Mac only", sticker: "Simplest start", fact: "Agents run on your Mac. They stop when it sleeps.", art: scenes.mac, tone: "sky" },
  hub: { name: "Mac + hub + node", sticker: "Agents work overnight", fact: "Two cloud devboxes stay on while your Mac sleeps.", art: scenes.hub, tone: "lilac" },
};

export function site(data: PageData, sizes: ArtSizes): Route[] {
  const repoUrl = `https://github.com/${data.engineRepo}`;
  const packOf = (name: string) => data.packs.find((pack) => pack.name === name)!;
  const roleOf = (pack: PagePack): Role => packCast[pack.name] ?? teamRole(pack.summary);
  const needsHub = (pack: PagePack) => data.needsHubPacks.includes(pack.name) && !data.hubStartPacks.includes(pack.name);
  const onByDefault = (pack: PagePack) => data.startPacks.includes(pack.name) || data.teamPacks.includes(pack.name);
  const icon = (name: string, size = "") => `<span class="icon ${size} ${brandIcons.has(name) ? "brand" : ""}">${packIcon(name)}</span>`;

  const image = (root: string, art: Art, eager = false) => {
    const size = sizes[art.file]!;
    return `<img src="${root}assets/art/${art.file}" width="${size.width}" height="${size.height}" alt="${esc(art.alt)}" decoding="async"${eager ? "" : ' loading="lazy"'}>`;
  };

  const stage = (root: string, art: Art, tone: Tone, eager = false) => `<div class="stage tone-${tone}">${image(root, art, eager)}</div>`;

  const posthogLogo = (root: string) =>
    `<picture><source srcset="${root}assets/art/${logos.dark}" media="(prefers-color-scheme: dark)"><img class="posthog" src="${root}assets/art/${logos.light}" width="160" height="28" alt="PostHog"></picture>`;

  const frame = ({ root, title, description, current, body, data: pageJson }: Frame) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>${esc(title)}</title>
<meta name="description" content="${esc(description)}">
<link rel="icon" type="image/svg+xml" href="data:image/svg+xml,${encodeURIComponent(logoMark)}">
<link rel="preconnect" href="https://fonts.googleapis.com">
<link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=IBM+Plex+Sans:wght@400;500;600;700&family=IBM+Plex+Mono:wght@400;500&display=swap">
<link rel="stylesheet" href="${root}assets/site.css">
</head>
<body>
<!-- Generated by scripts/build-page.ts from the pack data. Do not edit by hand. -->
<a class="skip" href="#main">Skip to the content</a>
<header class="top"><div class="wrap top-in">
  <a class="brand" href="${root}"><span class="mark" aria-hidden="true">${logoMark}</span><span>Fleet</span></a>
  <span class="byline"><span>a side project at</span>${posthogLogo(root)}</span>
  <nav aria-label="Site"><a href="${root}packs/"${current === "packs" ? ' aria-current="page"' : ""}>Packs</a><a href="${repoUrl}">GitHub</a><a class="btn btn-yellow small" href="${root}#start">Get started</a></nav>
</div></header>
<main id="main">
${body}
</main>
<footer class="foot"><div class="wrap foot-in">
  <div class="foot-brand"><a class="brand" href="${root}"><span class="mark" aria-hidden="true">${logoMark}</span><span>Fleet</span></a><p>The same agent setup on every machine.</p></div>
  <nav aria-label="More"><a href="${root}#start">Get started</a><a href="${root}packs/">Packs</a><a href="${repoUrl}">GitHub</a><a href="${repoUrl}#set-it-up-by-hand">Set it up by hand</a></nav>
  <p class="foot-note"><span>A side project at</span>${posthogLogo(root)}<span>The hedgehogs and the PostHog logo belong to PostHog.</span><a href="${repoUrl}/tree/main/page/art">Credits</a></p>
</div></footer>
${pageJson ? `<script id="fleet-data" type="application/json">${JSON.stringify(pageJson).replaceAll("<", "\\u003c")}</script>\n` : ""}<script src="${root}assets/app.js" defer></script>
</body>
</html>
`;

  const promptCard = (id: string, title: string, text: string, steps = "") => `<div class="prompt" id="${id}">
    <div class="prompt-head"><h3 id="${id}-title">${title}</h3>${steps}</div>
    <pre id="${id}-text" tabindex="0" aria-labelledby="${id}-title">${promptHtml(text)}</pre>
    <div class="prompt-foot"><button type="button" class="btn btn-yellow" data-copy="${id}-text">Copy prompt</button><a class="btn btn-ghost" id="${id}-t3" href="${t3Link(text)}" target="_blank" rel="noopener">Open in T3 Code${uiIcons.arrow}</a><span class="sr" role="status" id="${id}-status"></span></div>
  </div>`;

  const startSteps = `<ol class="mini-steps"><li><a href="https://t3.codes" target="_blank" rel="noopener">Download T3 Code</a></li><li>Sign in with T3 Connect</li><li>Paste this prompt</li></ol>`;

  const packRow = (where: Where, pack: PagePack, control: string) =>
    `<li class="row">${icon(pack.name, "mini")}<span class="row-text"><b>${esc(pack.title)}</b><span>${esc(roleOf(pack).line)}</span></span>${control.replace("{}", `${where}:${pack.name}`)}</li>`;

  const box = (root: string, where: Where) => {
    const { name, sticker, fact, art, tone } = boxes[where];
    const on = startPacksOn(data, firstStart);
    const switches = data.startPacks.map((pack) =>
      packRow(where, packOf(pack), `<input type="checkbox" role="switch" class="switch" name="{}" aria-label="${esc(packOf(pack).title)} in the ${name} setup"${on.includes(pack) ? " checked" : ""}>`),
    );
    const fixed = data.teamPacks.map((pack) => packRow(where, packOf(pack), `<span class="tag">Your team's pack</span>`));
    const hub = data.hubStartPacks.map((pack) =>
      where === "hub" ? packRow(where, packOf(pack), `<span class="tag on">Always on</span>`) : `<li class="row ghost">${icon(pack, "mini")}<span class="row-text"><b>${esc(packOf(pack).title)}</b><span>Add a hub later, when you want one.</span></span></li>`,
    );
    return `<section class="box" data-where="${where}">
      <input class="sr" type="radio" name="where" id="where-${where}" value="${where}"${firstStart.where === where ? " checked" : ""}>
      <label class="box-head" for="where-${where}"><span class="pick" aria-hidden="true"></span><span class="box-name">${name}</span><span class="sticker">${sticker}</span></label>
      ${stage(root, art, tone)}
      <p class="box-fact">${fact}</p>
      <ul class="rows" aria-label="Packs in the ${name} setup">${[...switches, ...fixed, ...hub].join("")}</ul>
    </section>`;
  };

  const landing = () => {
    const root = "./";
    const crewHtml = crew.map(({ pack, says }) => `<figure class="mate"><span class="bubble">${esc(says)}</span>${image(root, roleOf(packOf(pack)).art, true)}</figure>`).join("");
    const problems = scenes.problems.map(({ art, tone, title, line }) => `<li class="problem">${stage(root, art, tone)}<h3>${title}</h3><p>${line}</p></li>`).join("");
    const body = `<section class="hero"><div class="wrap hero-in">
  <div class="hero-text">
    <h1>Set up your <br>coding agents <br><mark>once</mark>.</h1>
    <p class="lead">Fleet gives every machine the same rules, skills, and workflows. One prompt sets it up.</p>
    <p class="cta"><a class="btn btn-yellow big" href="#start">Get started</a><a class="btn btn-line big" href="packs/">Browse the packs</a></p>
  </div>
  <div class="stage tone-blue crew" role="img" aria-label="${scenes.crew}">${crewHtml}</div>
</div></section>
<section class="band band-ink" aria-labelledby="problem-h"><div class="wrap">
  <header class="band-head"><p class="eyebrow">The problem</p><h2 id="problem-h">Good agents need a good setup.</h2></header>
  <ul class="problems">${problems}</ul>
</div></section>
<section class="band" aria-labelledby="fleet-h"><div class="wrap split">
  ${stage(root, scenes.fleet, "red")}
  <div class="split-text">
    <p class="eyebrow">What Fleet does</p>
    <h2 id="fleet-h">One prompt sets up all of it.</h2>
    <ul class="ticks">
      <li><span>It installs T3 Code, Claude Code, and Codex, with rules and skills.</span></li>
      <li><span>You pick the workflows as <b>packs</b>.</span></li>
      <li><span>It saves your answers in your private <b>profile</b> repo, so every machine matches.</span></li>
    </ul>
  </div>
</div></section>
<section class="band band-pick" id="start" aria-labelledby="start-h"><div class="wrap">
  <header class="band-head"><p class="eyebrow">Get started</p><h2 id="start-h">Where should your agents run?</h2><p class="lead">Choose a setup, and switch packs on or off. The prompt below changes as you choose.</p></header>
  <form id="chooser" class="chooser" autocomplete="off">
    <div class="boxes" role="radiogroup" aria-labelledby="start-h">${wheres.map((where) => box(root, where)).join("")}</div>
    ${promptCard("start", "Your Getting started prompt", startPrompt(data, firstStart), startSteps)}
  </form>
</div></section>`;
    return frame({
      root,
      title: "Fleet: set up your coding agents once",
      description: "Fleet gives every machine the same agent rules, skills, and workflows. Choose Mac only or a Mac with a hub and a node, and copy one prompt that sets it up.",
      body,
      data: promptData(data),
    });
  };

  const packTags = (pack: PagePack) =>
    [
      pack.always ? `<span class="tag on">On in every Fleet</span>` : "",
      onByDefault(pack) ? `<span class="tag on">On by default</span>` : "",
      needsHub(pack) ? `<span class="tag">Needs a hub</span>` : "",
      ...pack.requires.map((name) => `<span class="tag">Adds ${esc(packOf(name).title)}</span>`),
    ].join("");

  const packCard = (root: string, pack: PagePack) => {
    const role = roleOf(pack);
    const id = `pick-${pack.name}`;
    const name = `${icon(pack.name, "mini")}<span class="pack-name">${esc(pack.title)}</span>`;
    const head = pack.always
      ? `<div class="pack-main">${name}</div>`
      : `<input class="sr" type="checkbox" name="pack" id="${id}" value="${esc(pack.name)}"><label class="pack-main" for="${id}">${name}<span class="check" aria-hidden="true"></span></label>`;
    return `<li class="pack-card${pack.always ? " fixed" : ""}">
      ${stage(root, role.art, role.tone)}
      ${head}
      <p class="pack-line">${esc(role.line)}</p>
      <p class="pack-meta">${packTags(pack)}<a class="more" href="${esc(pack.name)}/" aria-label="${esc(pack.title)} details">Details${uiIcons.arrow}</a></p>
    </li>`;
  };

  const packs = () => {
    const root = "../";
    const body = `<section class="hero hero-small"><div class="wrap hero-in">
  <div class="hero-text">
    <h1>Extend your <mark>Fleet</mark>.</h1>
    <p class="lead">Select packs and copy one prompt. Your agent adds them to the Fleet you already run.</p>
    <p class="cta"><a class="link-arrow" href="${root}#start">No Fleet yet? Get started${uiIcons.arrow}</a></p>
  </div>
  ${stage(root, scenes.packs, "yellow", true)}
</div></section>
<section class="band band-tight"><div class="wrap">
  <form id="picker" class="picker" autocomplete="off">
    <ul class="pack-grid" aria-label="Packs">${data.packs.map((pack) => packCard(root, pack)).join("")}</ul>
    <aside class="tray" aria-label="Install prompt">
      <div class="tray-empty" id="install-empty">${image(root, scenes.empty)}<p><b>Select a pack.</b> The install prompt appears here.</p></div>
      <div id="install-full" hidden><p class="tray-count" id="install-count"></p>${promptCard("install", "Your install prompt", "")}</div>
    </aside>
    <a class="btn btn-yellow jump" id="install-jump" href="#install" hidden></a>
  </form>
</div></section>`;
    return frame({
      root,
      current: "packs",
      title: "Fleet packs: extend your Fleet",
      description: "Every Fleet pack on one page. Select the packs you want, and copy one prompt that adds them to the Fleet you already run.",
      body,
      data: promptData(data),
    });
  };

  const workflowItem = (workflow: PagePack["workflows"][number]) => {
    const needs = workflow.needs.map((need) => `<span class="tag">Needs ${esc(data.needLabels[need] ?? need)}</span>`).join("");
    const risk = workflow.risk ? `<details class="sub"><summary>Read before you turn it on</summary><p>${fmt(workflow.risk)}</p></details>` : "";
    return `<li class="wf"><div class="wf-head"><h3>${esc(workflow.name)}</h3><span class="tag ${workflow.default ? "on" : ""}">${workflow.default ? "On with the pack" : "Off until you turn it on"}</span>${needs}</div><p>${fmt(workflow.sentence)}</p>${risk}</li>`;
  };

  const settingItem = (setting: PagePack["settings"][number]) =>
    `<li><code>${esc(setting.key)}</code><span>${fmt(setting.question)}</span>${setting.default === undefined || setting.default === "" ? "" : `<span class="muted">Default: <code>${esc(setting.default)}</code></span>`}</li>`;

  const packPage = (pack: PagePack) => {
    const root = "../../";
    const role = roleOf(pack);
    const flow = packFlows[pack.name];
    const prompt = installPrompt(data, toggleSelected(data, [], pack.name));
    const add = pack.always
      ? `<section class="band band-tight" id="add"><div class="wrap"><p class="note">Every Fleet has this pack. You add nothing.</p></div></section>`
      : `<section class="band band-pick band-tight" id="add" aria-labelledby="add-h"><div class="wrap">
  <header class="band-head"><h2 id="add-h">Add ${esc(pack.title)} to your Fleet</h2><p class="lead">Paste this prompt into a T3 Code thread on a machine that runs Fleet.</p></header>
  ${promptCard("install", "Your install prompt", prompt)}
  <p class="after"><a class="link-arrow" href="../" data-select="${esc(pack.name)}">Add more packs in one prompt${uiIcons.arrow}</a></p>
</div></section>`;
    const body = `<section class="hero hero-small"><div class="wrap hero-in">
  <div class="hero-text">
    <a class="back" href="../">${uiIcons.arrow}All packs</a>
    <h1 class="pack-title">${icon(pack.name, "big")}<span>${esc(pack.title)}</span></h1>
    <p class="lead">${esc(pack.summary)}</p>
    <p class="tags">${packTags(pack)}</p>
    ${pack.always ? "" : `<p class="cta"><a class="btn btn-yellow big" href="#add">Add to your Fleet</a></p>`}
  </div>
  ${stage(root, role.art, role.tone, true)}
</div></section>
${flow ? `<section class="band band-tight" aria-labelledby="flow-h"><div class="wrap"><h2 id="flow-h">How it works</h2><ol class="flow">${flow.map((step) => `<li><span class="flow-step">${esc(step)}</span></li>`).join("")}</ol></div></section>` : ""}
${pack.workflows.length ? `<section class="band band-tight" aria-labelledby="wf-h"><div class="wrap"><h2 id="wf-h">Workflows</h2><ul class="wfs">${pack.workflows.map(workflowItem).join("")}</ul></div></section>` : ""}
<section class="band band-tight" aria-label="Cost and risk"><div class="wrap facts">
  ${pack.cost ? `<div class="fact"><p class="eyebrow">What it costs</p><p>${fmt(pack.cost)}</p></div>` : ""}
  ${pack.risk ? `<div class="fact warn"><p class="eyebrow">Know before you turn it on</p><p>${fmt(pack.risk)}</p></div>` : ""}
  ${pack.settings.length ? `<details class="fact settings"><summary><span class="eyebrow">Settings</span><span>${pack.settings.length === 1 ? "1 setting" : `${pack.settings.length} settings`} that your agent asks about</span></summary><ul>${pack.settings.map(settingItem).join("")}</ul></details>` : ""}
</div></section>
${add}`;
    return frame({ root, current: "packs", title: `${pack.title}: a Fleet pack`, description: pack.summary, body });
  };

  return [{ path: "index.html", html: landing() }, { path: "packs/index.html", html: packs() }, ...data.packs.map((pack) => ({ path: `packs/${pack.name}/index.html`, html: packPage(pack) }))];
}
